"""Generate the front-door demo assets from a real terminal run — never hand-typed.

Usage: python3 scripts/generate_demo_assets.py [--root REPO_ROOT]

Runs ``python -m toolkit.terminal demo.csv`` as a subprocess and writes:
- docs/demo-transcript.md — the full real output in a fenced block.
- docs/demo.svg — an animated SVG of the same output (lines fade in, in order).
- docs/demo.gif — the same output revealed line by line, rendered with PIL
  (if Pillow is installed) and saved as an animated GIF. Skipped with a
  plain message when Pillow is not available; the SVG + transcript are
  the primary assets and need only the standard library.

Re-run the script to regenerate; do not edit the outputs by hand.
"""
import argparse
import subprocess
import sys
from datetime import date
from pathlib import Path
from xml.sax.saxutils import escape

ROOT_DEFAULT = Path(__file__).resolve().parent.parent

# Lines that carry the whole story for the short demo: keep the header,
# the indicator snapshot, the setup matches and the Time-Machine verdict.
# The full output is in docs/demo-transcript.md; the SVG/GIF show these lines.
SVG_LINE_LIMIT = 40


def run_terminal(root):
    r = subprocess.run(
        [sys.executable, "-m", "toolkit.terminal", "demo.csv"],
        cwd=root, capture_output=True, text=True, check=False,
    )
    if r.returncode != 0:
        raise RuntimeError(f"terminal run failed (exit {r.returncode}):\n{r.stderr}")
    return r.stdout


def write_transcript(root, output):
    text = (
        "# Terminal demo — real output\n\n"
        "This file is generated by `scripts/generate_demo_assets.py` from a real\n"
        "run of the command below. Never edit the output block by hand; re-run\n"
        "the script instead.\n\n"
        "```bash\n"
        "python -m toolkit.terminal demo.csv\n"
        "```\n\n"
        f"Generated: {date.today().isoformat()}. The `demo.csv` file is synthetic\n"
        "example data (see the provenance lines at the top of `demo.csv`).\n\n"
        "```text\n"
        + output.rstrip("\n")
        + "\n```\n"
    )
    (root / "docs" / "demo-transcript.md").write_text(text, encoding="utf-8")


def _demo_lines(output):
    lines = output.splitlines()
    # Drop the trailing data-health note and footer for the short visual demo.
    keep = []
    for line in lines:
        if line.startswith("5. Data health"):
            break
        keep.append(line)
    return keep[:SVG_LINE_LIMIT]


def write_svg(root, output):
    lines = _demo_lines(output)
    char_w, font_size, line_h = 7.8, 13, 17
    width = int(max(len(line) for line in lines) * char_w) + 32
    height = len(lines) * line_h + 44
    parts = [
        (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
         'role="img" aria-label="Animated terminal demo of python -m toolkit.terminal demo.csv">'),
        '<rect width="100%" height="100%" rx="8" fill="#1e1e2e"/>',
        ('<circle cx="20" cy="16" r="5" fill="#f38ba8"/>'
         '<circle cx="38" cy="16" r="5" fill="#f9e2af"/>'
         '<circle cx="56" cy="16" r="5" fill="#a6e3a1"/>'),
        ('<text x="80" y="20" font-family="monospace" font-size="12" fill="#cdd6f4">'
         '$ python -m toolkit.terminal demo.csv</text>'),
        f'<g font-family="DejaVu Sans Mono, monospace" font-size="{font_size}" fill="#cdd6f4">',
    ]
    for i, line in enumerate(lines):
        y = 48 + i * line_h
        begin = f"{i * 0.12:.2f}s"
        parts.append(
            f'<text x="16" y="{y}" opacity="0">{escape(line) if line else " "}'
            f'<animate attributeName="opacity" from="0" to="1" '
            f'begin="{begin}" dur="0.15s" fill="freeze"/></text>'
        )
    parts.append("</g></svg>")
    (root / "docs" / "demo.svg").write_text("\n".join(parts) + "\n", encoding="utf-8")
    return len(lines)


def write_gif(root, output):
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        print("Pillow not installed — skipping docs/demo.gif (SVG + transcript done).")
        return None
    lines = _demo_lines(output)
    font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 13)
    bold = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", 13)
    char_w, line_h = 8, 17
    width = max(len(line) for line in lines) * char_w + 32
    height = len(lines) * line_h + 48
    step = 4  # lines revealed per frame
    frames = []
    for end in range(0, len(lines) + step, step):
        img = Image.new("RGB", (width, height), (30, 30, 46))
        d = ImageDraw.Draw(img)
        d.ellipse([12, 8, 24, 20], fill=(243, 139, 168))
        d.ellipse([30, 8, 42, 20], fill=(249, 226, 175))
        d.ellipse([48, 8, 60, 20], fill=(166, 227, 161))
        d.text((72, 8), "$ python -m toolkit.terminal demo.csv",
               font=bold, fill=(205, 214, 244))
        for i, line in enumerate(lines[:end]):
            d.text((16, 36 + i * line_h), line or " ", font=font, fill=(205, 214, 244))
        frames.append(img)
    durations = [150] * (len(frames) - 1) + [2500]
    frames[0].save(
        root / "docs" / "demo.gif", save_all=True,
        append_images=frames[1:], duration=durations, loop=0,
    )
    return len(frames)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(ROOT_DEFAULT))
    args = ap.parse_args()
    root = Path(args.root)
    output = run_terminal(root)
    write_transcript(root, output)
    n_lines = write_svg(root, output)
    n_frames = write_gif(root, output)
    print(f"wrote docs/demo-transcript.md ({len(output.splitlines())} output lines)")
    print(f"wrote docs/demo.svg ({n_lines} lines, animated)")
    if n_frames:
        print(f"wrote docs/demo.gif ({n_frames} frames)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
