"""Generate MODELS.md from a live walk-forward run — never hand-typed.

Usage: python3 scripts/generate_models_table.py [--root REPO_ROOT]
Writes MODELS.md next to the repo root. The series is synthetic and
labelled as such (fixed seed 7: trend + sine + Gaussian noise), so
every number in MODELS.md comes from a real walk_forward_report()
call on that series. Re-run the script to regenerate; do not edit
the table by hand.
"""
import argparse
import math
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from toolkit import predictive


def synthetic_series(n=120, seed=7):
    rng = random.Random(seed)
    out = []
    for i in range(n):
        out.append(round(100.0 + 0.15 * i + 5.0 * math.sin(i / 6.0)
                         + rng.gauss(0.0, 1.5), 4))
    return out


def _fmt(x):
    return f"{x:.4f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    args = ap.parse_args()
    root = Path(args.root)
    series = synthetic_series()
    report = predictive.walk_forward_report(series, 80, horizons=(1, 5))
    sched = predictive.retraining_schedule()
    regime = predictive.detect_regime(series, window=20)
    lines = []
    lines.append("# Model cards — walk-forward results")
    lines.append("")
    lines.append("Every number below was generated by "
                 "`scripts/generate_models_table.py` from a live "
                 "`predictive.walk_forward_report()` call. Nothing in this "
                 "file is hand-typed; re-run the script to regenerate it.")
    lines.append("")
    lines.append("## Data")
    lines.append("")
    lines.append("- Series: **synthetic** (fixed seed 7, 120 points): "
                 "100 + 0.15*t + 5*sin(t/6) + N(0, 1.5). Not real market data.")
    lines.append(f"- Train size: {report['train_size']} points; "
                 f"test: {120 - report['train_size']} points per horizon.")
    lines.append("- Baselines: naive (last value) on MAE; buy-and-hold and "
                 "index (here = buy-and-hold of the series itself, no "
                 "separate index supplied) on strategy return.")
    lines.append("- Verdict **edge** only when a model beats ALL THREE "
                 "baselines out of sample; otherwise **no edge**. "
                 "A 'no edge' verdict is published, not hidden.")
    lines.append("")
    for h in report["horizons"]:
        block = report["by_horizon"][h]
        lines.append(f"## Horizon {h} (n_test per model: "
                     f"{block['rows'][0]['n_test'] if block['rows'] else 0})")
        lines.append("")
        lines.append("| Model | MAE | RMSE | Beats naive | Strategy return | "
                     "Buy-and-hold | Index return | Verdict |")
        lines.append("|---|---:|---:|---|---:|---:|---:|---|")
        for row in block["rows"]:
            lines.append(
                f"| {row['model']} | {_fmt(row['mae'])} | {_fmt(row['rmse'])} | "
                f"{'yes' if row['beats_naive'] else 'no'} | "
                f"{_fmt(row['strategy_return'])} | "
                f"{_fmt(row['buy_and_hold_return'])} | "
                f"{_fmt(row['index_return'])} | {row['verdict']} |")
        lines.append("")
        lines.append(f"Models with an edge at horizon {h}: "
                     f"{block['n_edge']} of {len(block['rows'])}.")
        lines.append("")
    lines.append("## Regime at the end of the series (heuristic)")
    lines.append("")
    lines.append(f"- Label: **{regime['label']}** "
                 f"(latest std {regime['latest_std']:.4f}, median std "
                 f"{regime['median_std']:.4f}, trend {regime['trend']}).")
    lines.append(f"- Method: {regime['method']}.")
    lines.append("- This is a description of the recent window, NOT a "
                 "prediction.")
    lines.append("")
    lines.append("## Calibration")
    lines.append("")
    lines.append("- Probabilities are calibrated with Platt scaling "
                 "(`predictive.platt_calibrate`), fitted on out-of-sample "
                 "scores only, and reported with the Brier score before and "
                 "after calibration. No calibrated probability is published "
                 "without its Brier score.")
    lines.append("")
    lines.append("## Retraining")
    lines.append("")
    lines.append(f"- Cadence: {sched['cadence']}")
    lines.append("- Triggers:")
    for trigger in sched["triggers"]:
        lines.append(f"  - {trigger}")
    lines.append(f"- On trigger: {sched['on_trigger']}")
    lines.append(f"- Never: {sched['never']}")
    lines.append("")
    lines.append("## What this is not")
    lines.append("")
    lines.append("- Not investment advice. Past walk-forward MAE on a "
                 "synthetic series is not a guarantee of future accuracy, "
                 "and no model here is a buy/sell/hold signal.")
    (root / "MODELS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {root / 'MODELS.md'}")
    for h in report["horizons"]:
        block = report["by_horizon"][h]
        print(f"horizon {h}: {block['n_edge']}/{len(block['rows'])} models "
              f"with an edge")


if __name__ == "__main__":
    main()
