"""Tests for the capability matrix (Round 6, Step 0).

The matrix doc is GENERATED by scripts/generate_capability_matrix.py;
these tests pin the generator's contract, not the prose:
- all 15 reference repos are covered, with the exact teardown list;
- the summary counts equal the rows in the table;
- every "implemented" row links a test file that exists;
- every linked test file exists;
- the build plan lists exactly the seven named items, in rank order;
- the doc contains no marketing words;
- the stale-doc check works: the qa gate fails when the doc differs
  from a fresh render, and passes when it matches.
"""

import importlib.util
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "scripts"))

import generate_capability_matrix as gen

EXPECTED_REPOS = (
    "agency-agents", "augur", "day-trader-skill", "eigenledger",
    "finceptterminal", "finquant", "maybe", "multi-agent-market-research",
    "openbb", "qf-lib", "qlib", "quantinveststrats", "skfolio",
    "tradingagents", "union",
)

EXPECTED_BUILD_PLAN = (
    "Universe screener",
    "Second price source",
    "Volatility forecasting",
    "News and macro feed",
    "Derivatives and fixed income",
    "Local dashboard",
    "Pages demo with real global data",
)


def _load_qa():
    spec = importlib.util.spec_from_file_location(
        "qa_under_test", REPO_ROOT / "scripts" / "qa.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_all_fifteen_repos_covered():
    names = [name for name, _repo, _lic, _rows in gen.REPOS]
    assert names == list(EXPECTED_REPOS)
    assert len(names) == 15


def test_summary_counts_equal_table_rows():
    total, implemented, partial, not_planned = gen._counts()
    rows = [(s) for _n, _r, _l, rs in gen.REPOS for _c, s, _e, _t in rs]
    assert total == len(rows)
    assert implemented == rows.count("implemented")
    assert partial == rows.count("partial")
    assert not_planned == rows.count("not planned")
    assert implemented + partial + not_planned == total
    doc = gen.render()
    assert (f"{total} headline capabilities across 15 reference repos: "
            f"**{implemented} implemented**, **{partial} partial**, "
            f"**{not_planned} not planned**.") in doc


def test_every_implemented_row_links_an_existing_test():
    for _name, _repo, _lic, rows in gen.REPOS:
        for capability, status, _evidence, test in rows:
            if status == "implemented":
                assert test, f"implemented row has no test: {capability}"
                assert (REPO_ROOT / test).exists(), test


def test_every_linked_test_file_exists():
    for _name, _repo, _lic, rows in gen.REPOS:
        for _capability, _status, _evidence, test in rows:
            if test:
                assert (REPO_ROOT / test).exists(), test
                assert test.startswith("tests/test_")
                assert test.endswith(".py")


def test_statuses_are_only_the_three_allowed():
    for _name, _repo, _lic, rows in gen.REPOS:
        for _capability, status, _evidence, _test in rows:
            assert status in ("implemented", "partial", "not planned")


def test_build_plan_lists_the_seven_named_items_in_rank_order():
    items = [item for item, _i, _e, _w in gen.BUILD_PLAN]
    assert items == list(EXPECTED_BUILD_PLAN)
    doc = gen.render()
    ranks = re.findall(r"\| (\d) \| ([^|]+) \| (\d) \| (\d) \| ([\d.]+) \|",
                       doc)
    assert [item.strip() for _r, item, _i, _e, _ratio in ranks] == \
        list(EXPECTED_BUILD_PLAN)
    ratios = [float(ratio) for _r, _i, _a, _b, ratio in ranks]
    assert ratios == sorted(ratios, reverse=True)
    assert [int(r) for r, *_rest in ranks] == [1, 2, 3, 4, 5, 6, 7]


def test_build_plan_ratios_match_impact_over_effort():
    for item, impact, effort, _why in gen.BUILD_PLAN:
        assert 1 <= impact <= 5
        assert 1 <= effort <= 5
        doc = gen.render()
        match = re.search(
            rf"\| \d \| {re.escape(item)} \| {impact} \| {effort} \| "
            rf"({impact / effort:.2f}) \|", doc)
        assert match, item


def test_no_marketing_words():
    doc = gen.render().lower()
    for word in gen.BANNED_WORDS:
        assert word not in doc, word


def test_generated_doc_on_disk_is_fresh():
    assert gen.is_fresh(REPO_ROOT)
    on_disk = (REPO_ROOT / "docs" / "CAPABILITY-MATRIX.md").read_text(
        encoding="utf-8")
    assert on_disk == gen.render()


def test_stale_doc_fails_the_check(tmp_path):
    # A doc that differs from a fresh render must fail is_fresh — this
    # is the behaviour the qa gate depends on.
    docs = tmp_path / "docs"
    docs.mkdir()
    (docs / "CAPABILITY-MATRIX.md").write_text(
        gen.render() + "\nStale extra line.\n", encoding="utf-8")
    assert not gen.is_fresh(tmp_path)
    (docs / "CAPABILITY-MATRIX.md").write_text(
        gen.render(), encoding="utf-8")
    assert gen.is_fresh(tmp_path)


def test_qa_registers_the_capability_matrix_gate():
    qa = _load_qa()
    names = [name for name, _gate in qa.GATES]
    assert "capability-matrix" in names
    assert names.index("capability-matrix") > names.index("counts")
    assert names.index("capability-matrix") < names.index("fresh-clone")


def test_render_is_deterministic():
    assert gen.render() == gen.render()
